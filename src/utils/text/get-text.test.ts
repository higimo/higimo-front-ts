import { describe, it, expect } from 'vitest'

import { getText } from 'utils/text/get-text'

describe('getText', () => {
	describe('fallback на пустую строку', () => {
		it('возвращает "" для undefined', () => {
			expect(getText()).toBe('')
			expect(getText(undefined)).toBe('')
		})

		it('возвращает "" для пустой строки', () => {
			expect(getText('')).toBe('')
		})
	})

	describe('ветка с абзацами (</p>)', () => {
		it('возвращает содержимое первого абзаца', () => {
			expect(getText('<p>Первый</p><p>Второй</p>')).toBe('Первый')
		})

		it('снимает обрамляющие <p>…</p>', () => {
			expect(getText('<p>Единственный абзац</p>')).toBe('Единственный абзац')
		})

		it('обрезает пробелы вокруг первого абзаца', () => {
			expect(getText('<p>   Первый   </p><p>Второй</p>')).toBe('Первый')
		})

		it('пропускает пустой первый абзац и берёт следующий непустой', () => {
			expect(getText('<p></p><p>Второй</p>')).toBe('Второй')
		})

		it('пропускает несколько пустых абзацев подряд', () => {
			expect(getText('<p></p><p></p><p>Третий</p>')).toBe('Третий')
		})

		it('возвращает "" если все абзацы пустые', () => {
			expect(getText('<p></p><p></p>')).toBe('')
		})

		it('работает с переводом строк внутри абзаца', () => {
			expect(getText('<p>Первая строка\nВторая</p>')).toBe(
				'Первая строка\nВторая'
			)
		})

		it('при наличии только </p> не отрабатывает', () => {
			expect(getText('x</p>y\nz')).toBe('xy\nz')
		})

		it('не удаляет одиночные <p> внутри фрагмента', () => {
			expect(getText('<p>a<p>b</p>')).toBe('a')
		})

		it('не экранирует и не санитайзит HTML', () => {
			expect(getText('<p><script>alert(1)</script></p>')).toBe(
				'<script>alert(1)</script>'
			)
		})
	})

	describe('ветка с переводами строк (\\n)', () => {
		it('возвращает первую строку', () => {
			expect(getText('Первая строка\nВторая строка')).toBe(
				'Первая строка'
			)
		})

		it('возвращает первую строку при нескольких переводах', () => {
			expect(getText('Первая\nВторая\nТретья')).toBe('Первая')
		})

		it('не делает trim у первой строки', () => {
			expect(getText('  Первая  \nВторая')).toBe('  Первая  ')
		})

		it('оставляет \\r при Windows-переносах', () => {
			// \r\n → подстрока до \n, \r остаётся
			expect(getText('Первая\r\nВторая')).toBe('Первая\r')
		})
	})

	describe('когда ни абзацев, ни переводов строк', () => {
		it('возвращает строку как есть', () => {
			expect(getText('Просто текст')).toBe('Просто текст')
		})

		it('возвращает строку с пробелами как есть (trim не применяется)', () => {
			expect(getText('   hello   ')).toBe('   hello   ')
		})
	})

	describe('пограничные случаи: разделитель в позиции 0 (indexOf > 0)', () => {
		it('возвращает строку как есть, если </p> в самом начале', () => {
			expect(getText('</p>hello')).toBe('</p>hello')
		})

		it('возвращает строку как есть, если \\n в самом начале', () => {
			expect(getText('\nhello')).toBe('\nhello')
		})

		it('не делает fallback на ветку \\n, если </p> найден ровно в позиции 0', () => {
			// Проверка indexOf('</p>') > 0 ложна → идём в else if, там \n в позиции 5 → берём первую строку
			expect(getText('</p>a\nb')).toBe('</p>a')
		})

		it('возвращает "" для строки из одного </p>', () => {
			// indexOf('</p>') = 0, не > 0 → идём в else if, \n нет → возвращаем как есть
			expect(getText('</p>')).toBe('</p>')
		})
	})

	describe('чистота функции', () => {
		it('не мутирует исходную строку (строки неизменяемы, контракт)', () => {
			const input = '<p>Первый</p><p>Второй</p>'
			const output = getText(input)

			expect(input).toBe('<p>Первый</p><p>Второй</p>')
			expect(output).toBe('Первый')
		})

		it('идемпотентна: повторный вызов от результата даёт тот же результат', () => {
			const once = getText('<p>Первый</p><p>Второй</p>')
			const twice = getText(once)

			expect(twice).toBe(once)
		})
	})
})
